/** Prototype-local spacing tokens (candidates for the design system, Q5). */
object PrototypeSpacing {
    val screenPadding: Dp = 24.dp
    val stackGap: Dp = 16.dp
    val minTarget: Dp = 48.dp
    val contentMaxWidth: Dp = 480.dp
}

@Composable
fun PrototypeTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        content = content,
    )
}
